import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { root } from './environment.mjs';
import { validateBundle, siteConfig, siteTarget, remoteBundle, github, assertPromotion, writeBundle } from './site.mjs';
const target = process.argv[2];
const config = await siteConfig();
const selected = siteTarget(config, target);
const bundle = validateBundle({ html: await readFile(resolve(root, '.build/candidate/index.html'), 'utf8'), metadata: JSON.parse(await readFile(resolve(root, '.build/candidate/deployment.json'), 'utf8')) });
if (bundle.metadata.environment !== target) throw new Error('El candidato no corresponde al destino.');
const ref = await github('/git/ref/heads/' + selected.branch);
if (ref.object.sha !== bundle.metadata.commit) throw new Error('La rama cambió. Prepara una ejecución con el commit actualizado.');
const stable = await remoteBundle('');
const testing = target === 'production' ? await remoteBundle('pruebas/') : bundle;
if (target === 'production') assertPromotion(bundle.metadata, testing.metadata, await github('/actions/runs/' + testing.metadata.workflowRun));
const production = target === 'production' ? bundle : stable;
await writeBundle(resolve(root, '.build/site'), production);
await writeBundle(resolve(root, '.build/site/pruebas'), testing);
const manifest = { schemaVersion: 1, updated: target, production: production.metadata, testing: testing.metadata };
await writeFile(resolve(root, '.build/site/site-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
await mkdir(resolve(root, '.artifacts'), { recursive: true });
await writeFile(resolve(root, '.artifacts/publication.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Publicación de ${target} preparada; el otro ambiente conserva su HTML exacto.`);
