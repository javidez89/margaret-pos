import { resolve } from 'node:path';
import { root, loadEnvironment, requireLocalDemo } from './environment.mjs';
import { candidate, writeBundle } from './site.mjs';
import { findQuality } from './qa-evidence.mjs';
requireLocalDemo(await loadEnvironment());
const target = process.argv[2] || 'production';
if (target !== 'production') throw new Error('Las pruebas son locales; no se prepara una publicación pública de testing.');
const bundle = await candidate(target);
bundle.metadata.qa = await findQuality(bundle.metadata);
await writeBundle(resolve(root, '.build/candidate'), bundle);
console.log(`Candidato ${target} preparado con versión, commit y SHA-256.`);
